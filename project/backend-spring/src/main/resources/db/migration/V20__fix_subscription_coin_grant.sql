-- V20: 구독 코인 지급량 정정 (원치 → 코인 개수)
-- 배경: V19가 "코인 15,000원치 / 50,000원치"(KRW 상당액)를
--       coin_grant = 15000 / 50000 (= 코인 15,000개 / 50,000개)로 잘못 넣어,
--       코인 구매 번들 단가 대비 수천 배를 과지급하는 치명 버그였다.
-- 정정 근거: 코인 구매 번들 단가로 환산한다(번들 매칭).
--   - COIN_5  : 5코인  = 14,900원  → 15,000원치 ≈ 5코인  (Pro)
--   - COIN_20 : 22코인 = 49,900원  → 50,000원치 ≈ 22코인 (Premium)
-- V17의 "1원 = 1코인" 환산 가정은 폐기한다. V19는 이미 적용됐을 수 있어
-- (flyway checksum 충돌) 직접 수정하지 않고 본 V20에서 최종값으로 덮어쓴다.
-- 코인 번들(COIN_5/20/60 구매 팩)과 가격·과외 한도는 변경하지 않는다.

UPDATE subscription_plan
SET coin_grant = 5,
    features   = '["과외 2개 — 강의자료 전체 무제한 해제","코인 5개 즉시 지급 (약 15,000원 상당)","텔레그램 암기노트·과제·채점·총평","나만의 튜터 커스터마이징","학습 리포트로 약점 파악","완강 시 모의고사 1회 무료 (과외별)"]'::jsonb
WHERE code = 'pro';

UPDATE subscription_plan
SET coin_grant = 22,
    features   = '["과외 10개 — Pro의 모든 기능 포함","코인 22개 즉시 지급 (약 50,000원 상당)","모의고사 추가 2회 더 (총 3회)","우선 지원 — 가장 빠른 응답"]'::jsonb
WHERE code = 'premium';
